a1, a2 = np.kron(a, I), np.kron(I, a)
q1, p1 = (a1 + a1.T) / math.sqrt(2), (a1 - a1.T) / (1j * math.sqrt(2))
q2, p2 = (a2 + a2.T) / math.sqrt(2), (a2 - a2.T) / (1j * math.sqrt(2))
zs = [q1, p1, q2, p2]
Q = []
for k, l in itertools.combinations_with_replacement(range(4), 2):   # 10 Weyl-symmetrised quadratics
    Q.append((zs[k] @ zs[l] + zs[l] @ zs[k]) / 2)
print(f"  number of quadratic generators = {len(Q)} (= symmetric 4x4 = C(5,2))")
N1 = a1.T @ a1
N2 = a2.T @ a2
Ntot = np.diag(N1 + N2).real
low = np.where(Ntot <= 6)[0]                                      # stay far from the truncation edge


def blk(M):
    return M[np.ix_(low, low)]


# structure constants: [Q_k, Q_l] = i f^m_kl Q_m, fitted on the low block
Qv = np.array([blk(m).flatten() for m in Q]).T
f = np.zeros((10, 10, 10))
resid = 0.0
for k in range(10):
    for l in range(10):
        C = blk(Q[k] @ Q[l] - Q[l] @ Q[k]) / 1j
        sol, *_ = np.linalg.lstsq(Qv, C.flatten(), rcond=None)
        f[:, k, l] = sol.real
        resid = max(resid, np.abs(Qv @ sol - C.flatten()).max())
check("the 10 quadratics close under commutation (residual < 1e-9)", resid < 1e-9)
ad = [f[:, k, :] for k in range(10)]
K = np.array([[np.trace(ad[k] @ ad[l]) for l in range(10)] for k in range(10)])
ev = np.linalg.eigvalsh(K)
neg, pos = int((ev < -1e-9).sum()), int((ev > 1e-9).sum())
print(f"  Killing form: {neg} negative (compact), {pos} positive (non-compact)")
check("signature 4 compact + 6 non-compact = sp(4,R) = so(3,2), not so(4,1)", (neg, pos) == (4, 6))
Kinv = np.linalg.inv(K)
Cas = sum(Kinv[k, l] * (Q[k] @ Q[l]) for k in range(10) for l in range(10))
comm = max(np.abs(blk(Cas @ m - m @ Cas)).max() for m in Q)
idx = {(int(x), int(y)): low[i] for i, (x, y) in enumerate(zip(np.rint(np.diag(N1).real[low]), np.rint(np.diag(N2).real[low])))}
cas_vals = {s: Cas[idx[s], idx[s]].real for s in [(0, 0), (1, 0), (0, 1), (2, 0), (1, 1), (3, 0)]}
