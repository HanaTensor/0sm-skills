# ---- D4 the 10 in the algebra of 0SM's two axes (Dirac factorization, B1) ----
print("D4 Lie algebra generated by beta and alpha_i")
s0 = np.eye(2); sx = np.array([[0, 1], [1, 0]]); sy = np.array([[0, -1j], [1j, 0]]); sz = np.diag([1, -1])
Z = np.zeros((2, 2))
B = np.block([[s0, Z], [Z, -s0]]).astype(complex)                 # beta = gamma^0
A = [np.block([[Z, s], [s, Z]]).astype(complex) for s in (sx, sy, sz)]  # alpha_i


def span_dim(mats):
    if not mats:
        return 0
    M = np.array([m.flatten() for m in mats])
    M = np.concatenate([M.real, M.imag], axis=1)                  # real span
    return np.linalg.matrix_rank(M, tol=1e-9)


def close(gens):
    basis = list(gens)
    while True:
        new = [a @ b - b @ a for a, b in itertools.combinations(basis, 2)]
        d0 = span_dim(basis)
        cand = basis + new
        if span_dim(cand) == d0:
            return basis
        # keep an independent set
        keep = []
        for m in cand:
            if span_dim(keep + [m]) > span_dim(keep):
                keep.append(m)
        basis = keep


for label, gens in (("{beta, alpha_i}", [B] + A), ("{i beta, i alpha_i}", [1j * B] + [1j * a for a in A])):
    basis = close(gens)
    herm = sum(np.allclose(m, m.conj().T) for m in basis)
    anti = sum(np.allclose(m, -m.conj().T) for m in basis)
    print(f"  {label}: dimension {len(basis)}; Hermitian (non-compact) {herm}, anti-Hermitian (compact) {anti}")
    check(f"{label} closes into a 10-dimensional real Lie algebra", len(basis) == 10)
print("  6 compact + 4 non-compact = so(4,1) (de Sitter); all compact = so(5); complex form so(5,C) = sp(4,C).")
