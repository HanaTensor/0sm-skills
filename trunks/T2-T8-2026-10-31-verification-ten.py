import numpy as np

c = 299792458.0
hbar = 6.62607015e-34 / (2 * math.pi)
me = 9.1093837139e-31
G = 6.67430e-11
ae = 1.15965218059e-3
mP = math.sqrt(hbar * c / G)
lamCbar = hbar / (me * c)
beta = math.sqrt(1 - 1 / (1 + ae / math.sqrt(2))**2)

results = []


def check(name, cond):
    results.append(bool(cond))
    print(("  OK  " if cond else "  NG  ") + name)


