# タンパク質主鎖の重量組成（H は N=0 で寄与せず）
BACKBONE = [('C-12',12,6,6,0.50), ('O-16',16,8,8,0.23), ('N-14',14,7,7,0.16), ('S-32',32,16,16,0.01)]

def Tmax(A, E_MeV):
    """最大反跳 [eV]"""
    return 2*E_MeV**2/(A*u + 2*E_MeV)*1e6

def rate_pure(A, Q, thr, phi=None, Em=None, Emax=None):
    """純物質 1 kg あたりの事象率 [/kg/年]。phi 指定時は単色近似の線源。"""
    M = A*u; n = 1000.0/A*NA
    if phi is not None:
        Tm = Tmax(A, Emax)
        if Tm < thr: return 0.0
        s = GF**2*Q**2*(Em*1e-3)**2/(4*math.pi)*gev2cm2
        return phi*s*n*max(0.0, 1-thr/Tm)*yr
    tot = 0.0
    for _, p, E1, E2 in SOLAR:
        Tm = Tmax(A, E2)
        if Tm < thr: continue
        s = GF**2*Q**2*(E1*1e-3)**2/(4*math.pi)*gev2cm2
        tot += p*s*n*max(0.0, 1-thr/Tm)
    return tot*yr

def rate_target(gd_frac, thr, A_ion=160, Z_ion=64, N_ion=96, **kw):
    """実標的 1 kg あたり。束縛核の質量分率 gd_frac、残りは主鎖。"""
    r = gd_frac*rate_pure(A_ion, QW(Z_ion,N_ion), thr, **kw)
    for _, A, Z, N, w in BACKBONE:
        r += (1.0-gd_frac)*w*rate_pure(A, QW(Z,N), thr, **kw)
    return r

